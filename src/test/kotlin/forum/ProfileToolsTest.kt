    @Test
    fun `bio success without returned bio verifies a fresh profile`() = runBlocking<Unit> {
        MockForum { request ->
            if (request.method == "PUT") Reply("""{"success":"OK"}""") else Reply(profile("Verified bio"))
        }.use { server ->
            configure(server)
            invoke(tools(), "update_my_bio", """{"bio":"Verified bio"}""")
            val updateIndex = server.requests.indexOfFirst { it.method == "PUT" }
            assertTrue(updateIndex >= 0)
            assertTrue(server.requests.drop(updateIndex + 1).any { it.method == "GET" && it.path == SELF })
            assertEquals(1, server.requests.count { it.method == "PUT" })
            server.verify()
        }
    }

    @Test
    fun `clearing bio verifies missing fields and returns actual empty text`() = runBlocking<Unit> {
        for (bio in listOf("", " \n\t "))
        {
            MockForum { request ->
                Reply(profile(success = request.method == "PUT", includeBio = false))
            }.use { server ->
                configure(server)
