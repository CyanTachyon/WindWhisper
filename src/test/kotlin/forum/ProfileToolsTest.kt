                    buildJsonObject { put("bio", bio) }.toString())).jsonObject
                assertEquals(true, result.getValue("success").jsonPrimitive.boolean)
                assertEquals("", result.getValue("bio").jsonPrimitive.content)
                assertEquals(listOf("PUT" to SELF, "GET" to SELF), server.requests.map { it.method to it.path })
                assertEquals(bio, server.requests.first().json().getValue("bio_raw").jsonPrimitive.content)
                server.verify()
            }
        }
    }

    @Test
    fun `avatar pick requires explicit success even on HTTP 200`() = runBlocking<Unit> {
        val store = imageStore()
        MockForum { request ->
            when (request.path)
            {
                SELF -> Reply(profile())
                "/uploads.json" -> Reply("""{"id":321}""")
                PICK -> Reply("""{"errors":["avatar denied"]}""")
                else -> Reply("{}", 404)
            }
        }.use { server ->
            configure(server)
            val error = assertFailsWith<Exception> { invoke(tools(store), "update_my_avatar", """{"imageId":"ig_avatar"}""") }
            assertContains(error.message.orEmpty(), "avatar denied")
            assertEquals(1, server.requests.count { it.path == PICK })
            server.verify()
        }
    }

    private fun configure(server: MockForum)
    {
        mainConfig = MainConfig(server.url, "fixture-user", "fixture-password", 3, emptyMap(), emptyMap())
    }

    private fun directory(): File = Files.createTempDirectory("windwhisper-profile-tools-").toFile().also(directories::add)

    private fun imageStore(directory: File = directory()): GeneratedImageStore
    {
        val bytes = ByteArrayOutputStream().use { output ->
            assertTrue(ImageIO.write(BufferedImage(2, 2, BufferedImage.TYPE_INT_RGB), "png", output))
            output.toByteArray()
        }
        return GeneratedImageStore(directory).apply { save("ig_avatar", Base64.getEncoder().encodeToString(bytes), "png") }
    }

    private fun profile(bio: String = "Existing bio", success: Boolean = false, includeBio: Boolean = true): String = buildJsonObject {
        if (success) put("success", "OK")
        putJsonObject("user") {
            put("id", 47)
            put("username", "fixture-user")
            if (includeBio) put("bio_raw", bio)
            put("avatar_template", "/user_avatar/forum/fixture-user/{size}/12.png")
            put("email", "private@example.com")
            put("session", "session-secret")
            put("api_key", "api-secret")
        }
    }.toString()

    private suspend fun tools(images: GeneratedImageStore? = null): List<AiToolInfo<*>> =
        AiToolSet(Profile(LoginData("forum-session=fixture", "csrf-fixture"), images)).getTools(null, AiConfig.LlmModel())

    private suspend fun invoke(tools: List<AiToolInfo<*>>, name: String, args: String): String =
        tools.single { it.name == name }(args) {}.content.toText()

    private data class Request(val method: String, val path: String, val headers: Map<String, List<String>>, val body: ByteArray)
    {
        fun header(name: String): String? = headers.entries.firstOrNull { it.key.equals(name, true) }?.value?.firstOrNull()
        fun json(): JsonObject = Json.parseToJsonElement(body.toString(Charsets.UTF_8)).jsonObject
    }

    private data class Reply(val body: String, val status: Int = 200)

    private class MockForum(handler: (Request) -> Reply): AutoCloseable
    {
        val requests = CopyOnWriteArrayList<Request>()
        private val failures = CopyOnWriteArrayList<Throwable>()
        private val server = HttpServer.create(InetSocketAddress("127.0.0.1", 0), 0).apply {
            createContext("/") { exchange ->
                try
                {
                    val request = Request(exchange.requestMethod, exchange.requestURI.path, exchange.requestHeaders.toMap(), exchange.requestBody.readBytes())
                    requests += request
                    val reply = handler(request)
                    val bytes = reply.body.toByteArray(Charsets.UTF_8)
                    exchange.responseHeaders.add("Content-Type", "application/json")
                    exchange.sendResponseHeaders(reply.status, bytes.size.toLong())
                    exchange.responseBody.write(bytes)
                }
                catch (error: Throwable) { failures += error }
                finally { exchange.close() }
            }
            start()
        }
        val url: String get() = "http://127.0.0.1:${server.address.port}"
        fun verify() { failures.firstOrNull()?.let { throw AssertionError("Mock forum failed", it) } }
        override fun close() { server.stop(0) }
    }

    companion object
    {
        private const val SELF = "/u/fixture-user.json"
        private const val PICK = "/u/fixture-user/preferences/avatar/pick.json"
    }
}
