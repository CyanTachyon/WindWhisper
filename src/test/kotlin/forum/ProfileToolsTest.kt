{
    private val directories = mutableListOf<File>()
    private var previousConfig: MainConfig? = null

    @BeforeTest
    fun setUp()
    {
        initializeTestEnvironment()
        previousConfig = runCatching { mainConfig }.getOrNull()
    }

    @AfterTest
    fun tearDown()
    {
        previousConfig?.let { mainConfig = it }
        directories.forEach { it.deleteRecursively() }
    }

    @Test
    fun `read own profile excludes unrelated private account fields`() = runBlocking<Unit> {
        MockForum { Reply(profile("A short bio")) }.use { server ->
            configure(server)
            val result = invoke(tools(), "get_my_profile", "{}")
            assertContains(result, "fixture-user")
            assertContains(result, "A short bio")
            assertContains(result, "/user_avatar/forum/fixture-user/{size}/12.png")
            assertFalse("private@example.com" in result)
            assertFalse("session-secret" in result)
            assertFalse("api-secret" in result)
            assertEquals(listOf("GET" to SELF), server.requests.map { it.method to it.path })
            server.verify()
        }
    }

    @Test
    fun `own profile with omitted blank biography returns an empty bio`() = runBlocking<Unit> {
        MockForum { Reply(profile(includeBio = false)) }.use { server ->
            configure(server)
            val result = Json.parseToJsonElement(invoke(tools(), "get_my_profile", "{}")).jsonObject
            assertEquals("", result.getValue("bio").jsonPrimitive.content)
            assertEquals("fixture-user", result.getValue("username").jsonPrimitive.content)
            assertEquals(listOf("GET" to SELF), server.requests.map { it.method to it.path })
            server.verify()
        }
    }

    @Test
    fun `bio update targets own account and changes only exact bio including empty text`() = runBlocking<Unit> {
        for (bio in listOf("  Hello **world**!\n第二行  ", ""))
        {
            MockForum { request ->
                if (request.method == "PUT") Reply(profile(bio, success = true)) else Reply(profile("before"))
            }.use { server ->
                configure(server)
                invoke(tools(), "update_my_bio", buildJsonObject { put("bio", bio) }.toString())
                val request = server.requests.single { it.method == "PUT" }
                assertEquals(SELF, request.path)
                assertEquals(buildJsonObject { put("bio_raw", bio) }, request.json())
                assertEquals("forum-session=fixture", request.header("Cookie"))
                assertEquals("csrf-fixture", request.header("X-Csrf-Token"))
                assertTrue(server.requests.all { it.path == SELF })
                server.verify()
            }
        }
    }

    @Test
    fun `model cannot choose another account or arbitrary uploaded avatar`() = runBlocking<Unit> {
        val store = imageStore()
        MockForum { Reply("{}") }.use { server ->
            configure(server)
            val tools = tools(store)
            listOf(
                "get_my_profile" to """{"username":"another-user"}""",
                "update_my_bio" to """{"bio":"new","username":"another-user"}""",
                "update_my_avatar" to """{"imageId":"ig_avatar","userId":999}""",
                "update_my_avatar" to """{"imageId":"ig_avatar","uploadId":999}""",
            ).forEach { (name, args) ->
                assertFailsWith<Exception> { invoke(tools, name, args) }
            }
            assertTrue(server.requests.isEmpty())
            server.verify()
        }
    }

    @Test
    fun `avatar uploads validated generated bytes for own user then picks returned upload`() = runBlocking<Unit> {
        val store = imageStore()
        MockForum { request ->
            when (request.path)
            {
                SELF -> Reply(profile())
                "/uploads.json" -> Reply("""{"id":321,"url":"/uploads/default/original/1X/avatar.png","width":2,"height":2}""")
                PICK -> Reply("""{"success":"OK"}""")
                else -> Reply("{}", 404)
            }
        }.use { server ->
            configure(server)
            invoke(tools(store), "update_my_avatar", """{"imageId":"ig_avatar"}""")
            assertEquals(listOf("GET" to SELF, "POST" to "/uploads.json", "PUT" to PICK),
                server.requests.take(3).map { it.method to it.path })
            val upload = server.requests.single { it.path == "/uploads.json" }
            assertEquals("forum-session=fixture", upload.header("Cookie"))
            assertEquals("csrf-fixture", upload.header("X-Csrf-Token"))
            val contentType = upload.header("Content-Type")!!
            assertTrue(contentType.startsWith("multipart/form-data; boundary="))
            val multipart = upload.body.toString(Charsets.ISO_8859_1)
            val parts = multipart.split("--" + contentType.substringAfter("boundary=").trim('"'))
            fun part(name: String) = parts.single { Regex("""name="?$name"?(?:;|\r\n)""").containsMatchIn(it) }
            fun value(name: String) = part(name).substringAfter("\r\n\r\n").trimEnd('\r', '\n')
            assertEquals("avatar", value("upload_type"))
            assertFalse(Regex("""name="?(?:user_id|type)"?(?:;|\r\n)""").containsMatchIn(multipart))
            assertEquals("true", value("synchronous"))
            assertContains(part("file"), "Content-Type: image/png")
            assertContains(part("file"), store.read("ig_avatar").bytes.toString(Charsets.ISO_8859_1))
            assertEquals(buildJsonObject { put("type", "uploaded"); put("upload_id", 321) },
                server.requests.single { it.path == PICK }.json())
            assertFalse(server.requests.any { it.path == "/posts.json" })
            server.verify()
        }
    }

    @Test
    fun `invalid unknown or corrupted generated image never reaches forum`() = runBlocking<Unit> {
        val directory = directory()
        val store = imageStore(directory)
        MockForum { Reply(profile()) }.use { server ->
            configure(server)
            val tools = tools(store)
            for (id in listOf("../outside", "ig_missing"))
                assertFailsWith<Exception> { invoke(tools, "update_my_avatar", buildJsonObject { put("imageId", id) }.toString()) }
            directory.listFiles()!!.single().writeText("not an image")
            assertFailsWith<Exception> { invoke(tools, "update_my_avatar", """{"imageId":"ig_avatar"}""") }
            assertTrue(server.requests.isEmpty())
            assertTrue(tools(null).none { it.name == "update_my_avatar" })
            server.verify()
        }
    }

    @Test
    fun `rate limits reach model with original body and no write replay`() = runBlocking<Unit> {
        val store = imageStore()
        val errorBody = """{"errors":["请等待再修改"],"error_type":"rate_limit","extras":{"wait_seconds":5}}"""
        listOf("update_my_bio", "update_my_avatar").forEach { name ->
            MockForum { request ->
                if (request.method == "GET") Reply(profile()) else Reply(errorBody, 429)
            }.use { server ->
                configure(server)
                val args = if (name == "update_my_bio") """{"bio":"A new bio"}""" else """{"imageId":"ig_avatar"}"""
                val result = withTimeout(5_000) {
                    parseToolCalls(mapOf("call_profile" to (name to args)), tools(store)) {}
                }.single()
                val output = Json.parseToJsonElement(result.content.toText()).jsonObject
                assertEquals(false, output["ok"]!!.jsonPrimitive.boolean)
                val message = output["error"]!!.jsonObject["message"]!!.jsonPrimitive.content
                assertContains(message, "429")
                assertContains(message, errorBody)
                assertEquals(1, server.requests.count { it.method != "GET" })
                assertFalse(server.requests.any { it.path == PICK })
                server.verify()
            }
        }
    }

    @Test
    fun `avatar pick failure is surfaced without repeating upload or selection`() = runBlocking<Unit> {
        val store = imageStore()
        val errorBody = """{"errors":["头像被论坛拒绝"]}"""
        MockForum { request ->
            when (request.path)
            {
                SELF -> Reply(profile())
                "/uploads.json" -> Reply("""{"id":321}""")
                PICK -> Reply(errorBody, 422)
                else -> Reply("{}", 404)
            }
        }.use { server ->
            configure(server)
            val error = assertFailsWith<Exception> { invoke(tools(store), "update_my_avatar", """{"imageId":"ig_avatar"}""") }
            assertContains(error.message.orEmpty(), "422")
            assertContains(error.message.orEmpty(), errorBody)
            assertEquals(1, server.requests.count { it.path == "/uploads.json" })
            assertEquals(1, server.requests.count { it.path == PICK })
            server.verify()
        }
    }

